    def run(self, context: dict) -> dict:
        """Обработать входящий запрос клиента и подготовить черновики ответов."""
        user_msg = self._build_user_message(context)
        messages = [{"role": "user", "content": user_msg}]
        _, tool_store = self._run_loop(messages)

        analyses = tool_store.get("analyze_request", [{}])
        drafts = sorted(
            tool_store.get("draft_response", []),
            key=lambda d: d.get("message_number", 99),
        )
        next_steps = tool_store.get("set_next_steps", [{}])

        analysis = analyses[0] if analyses else {}

        return {
            "client_name": analysis.get("client_name", ""),
            "request_quality": analysis.get("request_quality", ""),
            "deadline_status": analysis.get("deadline_status", ""),
            "items_requested": analysis.get("items_requested", []),
            "items_out_of_scope": analysis.get("items_out_of_scope", []),
            "info_missing": analysis.get("info_missing", []),
            "risks": analysis.get("risks", []),
            "loss_analysis": analysis.get("loss_analysis", ""),
            "analysis": analysis,
            "draft_messages": drafts,
            "next_steps": next_steps[0] if next_steps else {},
            # поля для совместимости с оркестратором
            "requirements": analysis,
            "status": {
                "request_quality": analysis.get("request_quality", ""),
                "deadline_status": analysis.get("deadline_status", ""),
            },
        }
