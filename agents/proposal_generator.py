    def run(self, context: dict) -> dict:
        """Сгенерировать КП на основе данных калькулятора и заявки клиента."""
        user_msg = self._build_user_message(context)
        messages = [{"role": "user", "content": user_msg}]
        _, tool_store = self._run_loop(messages)

        proposal = tool_store.get("set_proposal", [{}])[0]
        notes = tool_store.get("add_note", [])

        return {
            "proposal": proposal,
            "message_text": proposal.get("message_text", ""),
            "client_name": proposal.get("client_name", ""),
            "total_price_min": proposal.get("total_price_min", 0),
            "total_price_max": proposal.get("total_price_max", 0),
            "is_preliminary": proposal.get("is_preliminary", True),
            "items_included": proposal.get("items_included", []),
            "items_excluded": proposal.get("items_excluded", []),
            "notes": notes,
        }
